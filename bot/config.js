export function getConfig(env = process.env) {
    const list = (text, fallback = []) => text ? [...new Set(text.split(/[|,]/).map(s => s.trim()).filter(Boolean))] : fallback;
    const profileKey = (env.BOT_PROFILE || '').toLowerCase().trim();
    const profile = PROFILES[profileKey] || {};

    const defaultGenerated = profile.generatedOptions || [
        'Myself',
        'Leadgen team',
        'qooob',
        'Promoters',
        'External Introducers',
        'Others',
    ];

    return {
        profile: profileKey,
        botName: env.BOT_NAME || profile.botName || '',
        icpOptions: list(env.ICP_TYPE_OPTIONS, ['Operator', 'Platform', 'Provider', 'Aggregator', 'B2B Tech Solution', 'B2B Professional Services']),
        generatedOptions: profileKey==='onlyplay'?profile.generatedOptions:env.GENERATED_BY_OPTIONS ? list(env.GENERATED_BY_OPTIONS) : defaultGenerated,
        cardFooter: env.CARD_FOOTER !== undefined ? env.CARD_FOOTER : (profile.cardFooter || ''),
        event: env.EVENT_NAME || '',
        timeZone: env.TIMEZONE || 'UTC',
        bookingUrlFile: env.BOOKING_URL_FILE || '',
        sharedLeads: env.SHARED_LEADS === 'true',
        calendarAccountsDir: env.CALENDAR_ACCOUNTS_DIR || '',
        googleOauthPublicUrl: env.GOOGLE_OAUTH_PUBLIC_URL || 'https://onlyplay.5.22.222.83.sslip.io',
        requireCalendarConnection: env.REQUIRE_CALENDAR_CONNECTION === 'true',
        adminSettingsFile: env.ADMIN_SETTINGS_FILE || '',
        reminderLedgerFile: env.REMINDER_LEDGER_FILE || '',
        adminIds: list(env.ADMIN_TELEGRAM_USER_IDS),
        allowedUsers: list(env.ALLOWED_TELEGRAM_USER_IDS),
        accessPassword: env.ACCESS_PASSWORD ? String(env.ACCESS_PASSWORD).trim() : '',
        accessPasswords: list(env.ACCESS_PASSWORDS),
    };
}
