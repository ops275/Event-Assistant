test('Website compact label preserves complete href including query, fragment and HTTP',()=>{
 const lead=fixture();
 for(const [url,href,label] of [
  ['https://example.com/demo/3?x=1&y=2#team','https://example.com/demo/3?x=1&amp;y=2#team','example.com/demo/3?x=1&amp;y=2#team'],
  ['http://example.com:8080/a%2Fb?q=a%20b#x','http://example.com:8080/a%2Fb?q=a%20b#x','example.com:8080/a%2Fb?q=a%20b#x'],
  ['example.com/path?q=1#x','https://example.com/path?q=1#x','example.com/path?q=1#x'],
  ['HTTPS://Example.com/X','HTTPS://Example.com/X','Example.com/X']
 ]){lead.fields.website=url;const before=structuredClone(lead);assert.ok(card(lead).text.startsWith('<b>Demo Pixel Games</b> | <a href="'+href+'">'+label+'</a>'));assert.deepEqual(lead,before);}
});
test('HTML in names and URLs is escaped; unsafe schemes stay plain text',()=>{
 const lead=fixture();lead.actorName='Alice <Creator> & Co';lead.fields.website='https://example.com/a?x="<tag>&y=1';
 const text=card(lead).text;
 assert.match(text,/by Alice &lt;Creator&gt; &amp; Co/);
 assert.ok(text.includes('href="https://example.com/a?x=&quot;&lt;tag&gt;&amp;y=1"'));
 assert.ok(text.includes('>example.com/a?x="&lt;tag&gt;&amp;y=1</a>'));
 for(const input of ['javascript:alert(1)','data:text/html,<b>hi</b>','ftp://example.com/file','https://','https://example.com/\tbad']){lead.fields.website=input;assert.doesNotMatch(card(lead).text,/<a href=/);}
});
test('multiple websites have separate complete links and long targets remain intact',()=>{
 const lead=fixture();const long='https://example.com/'+('a'.repeat(260))+'?q=1#tail';
 lead.fields.website='https://example.com/one\nhttp://example.org/two\n'+long;
 const text=card(lead).text;
 assert.ok(text.includes('<a href="https://example.com/one">example.com/one</a>'));
 assert.ok(text.includes('<a href="http://example.org/two">example.org/two</a>'));
 assert.ok(text.includes('href="'+long+'"'));assert.ok(text.includes('...</a>'));
 assert.ok(text.includes('+1 202 555 0103'));assert.ok(text.includes('sofia@example.com'));assert.ok(text.includes('https://example.com/linkedin/sofia'));
 assert.ok(text.length<4096);
});
