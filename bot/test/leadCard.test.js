test('hundreds of websites keep the existing 180-character display budget without cutting HTML anchors',()=>{
 const lead=fixture();lead.fields.website=Array.from({length:700},(_,i)=>'https://example.com/'+i).join('\n');
 const first=card(lead).text.split('\n')[0];const visible=first.replace(/<[^>]*>/g,'');
 assert.ok(visible.length<='Demo Pixel Games | '.length+180);
 assert.equal((first.match(/<a /g)||[]).length,(first.match(/<\/a>/g)||[]).length);
 assert.ok(first.endsWith('...'));assert.ok(first.includes('href="https://example.com/0"'));
});
