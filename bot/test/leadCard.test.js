import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createLead} from '../flow.js';
import {render, fullText} from '../ui.js';
import {FileStore} from '../services/store.js';
import {projectHandoffs, handoffForRole} from '../services/handoffJournal.js';

const config={profile:'onlyplay',role:'partnership'};
function fixture(){
 const lead=createLead('101:101','@alice','Test event',{id:101,username:'alice',firstName:'Alice',lastName:'Creator'});
 Object.assign(lead.fields,{company:'Demo Pixel Games',icp:'Provider',generatedBy:'Myself',fullName:'Demo Contact',website:'https://example.com/demo/3?x=1&y=2#team',phone:'+1 202 555 0103',email:'sofia@example.com',linkedin:'https://example.com/linkedin/sofia'});
 return lead;
}
function card(lead,extra={}){return render(lead,{view:'review',nonce:'test',cardFromSearch:true},{...config,...extra});}
test('Myself shows the saved creator, never viewer or assignee, without mutating the lead',()=>{
 const lead=fixture();lead.assigneeId='202';const before=structuredClone(lead);
 for(const role of ['partnership','leadgen','admin']){
  const panel=card(lead,{role,actorName:'Bob Viewer'});
  assert.match(panel.text,/Provider by Alice Creator/);assert.doesNotMatch(panel.text,/by Myself|Bob Viewer/);
  assert.equal(panel.parseMode,'HTML');
  assert.ok(panel.rows.flat().some(b=>b.text==='Hand off this lead'));
  assert.ok(panel.rows.flat().some(b=>b.text==='Add\/Edit'));
  assert.ok(panel.rows.flat().some(b=>b.text==='Delete lead'));
 }
 assert.deepEqual(lead,before);
});
test('creator snapshot survives persisted reopen, shared search selection and actual handoff projection',()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'onlyplay-card-'));
 try{
  const store=new FileStore(dir);const lead=fixture();store.state.leads[lead.id]=lead;store.save();
  const reopened=new FileStore(dir);reopened.sharedLeads=true;
  assert.match(card(reopened.lead('202:202',lead.id)).text,/Provider by Alice Creator/);
  const id='ea'+'a'.repeat(64),at='2026-10-28T10:00:00.000Z';
  const record={id,leadId:lead.id,status:'confirmed',createdAt:at,confirmedAt:at,sender:{id:'303',name:'Sender'},creator:{id:'101',name:'Alice Creator'},receiver:{id:'202',name:'Bob Receiver'},calendar:{id:'primary',timeZone:'UTC'},receiverCalendar:{id:'bob',timeZone:'UTC'},meetingType:'online',description:'Test',guests:[],notifications:{},fingerprint:'b'.repeat(64),inbox:false,request:{id,summary:'Meeting',description:'Test',location:'',start:{dateTime:at},end:{dateTime:'2026-10-28T10:30:00.000Z'},attendees:[],extendedProperties:{private:{handoffId:id}}},event:{id}};
  projectHandoffs(reopened.state,[record]);
  assert.equal(reopened.state.leads[lead.id].assigneeId,'202');
  for(const owner of ['101:101','202:202'])assert.match(card(handoffForRole(reopened.lead(owner,lead.id),'partnership')).text,/Provider by Alice Creator/);
  reopened.save();assert.match(card(new FileStore(dir).state.leads[lead.id]).text,/Provider by Alice Creator/);
 }finally{fs.rmSync(dir,{recursive:true,force:true});}
});
