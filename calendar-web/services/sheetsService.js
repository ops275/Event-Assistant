import { UserError } from '../flow.js';
import { serialQueue } from './store.js';

export const SHEET_FIELDS = [
    ['fullName', 'Full name'], ['company', 'Company'], ['icp', 'ICP Type'], ['generatedBy', 'Generated By'],
    ['context', 'Meeting context'], ['history', 'Previous correspondence'], ['nextSteps', 'Next steps'],
    ['jobTitle', 'Job title'], ['phone', 'Telephone / WhatsApp'], ['telegram', 'Telegram'], ['email', 'Email'],
    ['website', 'Website'], ['linkedin', 'LinkedIn'], ['address', 'Address'], ['otherContacts', 'Other contacts'],
];
export const SHEET_HEADERS = [
    ...SHEET_FIELDS.map(([, title]) => title),
    'Submitted by', 'Telegram username', 'Telegram user ID', 'Status',
    'Created date', 'Created time', 'Updated date', 'Updated time', 'Lead ID',
];
const writeQueue = serialQueue();
export const quoteSheet = title => "'" + title.replace(/'/g, "''") + "'";

export function formatDateTime(isoString, timeZone = process.env.TIMEZONE || Intl.DateTimeFormat().resolvedOptions().timeZone) {
    if (!isoString) return { date: '', time: '' };
    try {
        const d = new Date(isoString);
        if (isNaN(d.getTime())) return { date: String(isoString), time: '' };
        const date = new Intl.DateTimeFormat('ru-RU', {
            day: '2-digit', month: '2-digit', year: 'numeric', timeZone,
        }).format(d);
        const time = new Intl.DateTimeFormat('ru-RU', {
            hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false, timeZone,
        }).format(d);
        return { date, time };
    } catch {
        const [d, rest] = String(isoString).split('T');
        return { date: d || '', time: rest?.slice(0, 8) || '' };
    }
}

function cell(value) {
    const text = String(value || '');
    return text.length > 45000 ? text.slice(0, 44900) + '\n[Full text in local lead export]' : text;
}

export function sheetRow(lead, env = process.env) {
    const legacyUsername = String(lead.actor || '').startsWith('@') ? lead.actor : '';
    const legacyUserId = String(lead.owner || '').split(':').at(-1) || '';
    const created = formatDateTime(lead.createdAt, env?.TIMEZONE);
    const updated = formatDateTime(lead.updatedAt, env?.TIMEZONE);
    return [...SHEET_FIELDS.map(([key]) => lead.fields[key] || ''),
        lead.actorName || lead.actor, lead.actorUsername || legacyUsername, lead.actorId || legacyUserId,
        lead.status || 'draft', created.date, created.time, updated.date, updated.time, lead.id].map(cell);
}

function columnName(number) {
    let name = '';
    while (number > 0) { number--; name = String.fromCharCode(65 + (number % 26)) + name; number = Math.floor(number / 26); }
    return name;
}

export function createSheetsService({ env = process.env, client } = {}) {
    const configured = () => Boolean(client || (env.GOOGLE_SERVICE_ACCOUNT_EMAIL && env.GOOGLE_PRIVATE_KEY && env.GOOGLE_SHEET_ID));
    let sheets = client;
    async function getClient() {
        if (!configured()) throw new UserError('Google Sheets is not connected yet. Lead saved locally.');
        if (!sheets) {
            const { google } = await import('googleapis');
            const auth = new google.auth.GoogleAuth({
                credentials: {
                    client_email: env.GOOGLE_SERVICE_ACCOUNT_EMAIL,
                    private_key: env.GOOGLE_PRIVATE_KEY.replace(/\\n/g, '\n'),
                },
                scopes: ['https://www.googleapis.com/auth/spreadsheets'],
            });
            sheets = google.sheets({ version: 'v4', auth });
        }
        return sheets;
    }

    async function save(lead) {
        const spreadsheetId = env.GOOGLE_SHEET_ID;
        return writeQueue(spreadsheetId || 'test', async () => {
            const api = await getClient();
            const title = env.GOOGLE_SHEET_TAB || 'Event Assistant v2';
            const range = quoteSheet(title);
            const options = { timeout: 30000, retry: false };
            const meta = await api.spreadsheets.get({ spreadsheetId }, options);
            if (!meta.data.sheets?.some(s => s.properties.title === title)) {
                await api.spreadsheets.batchUpdate({ spreadsheetId, requestBody: { requests: [{ addSheet: { properties: {
                    title, gridProperties: { columnCount: SHEET_HEADERS.length, frozenRowCount: 1 },
                } } }] } }, options);
            }
            const header = await api.spreadsheets.values.get({ spreadsheetId, range: range + '!1:1' }, options);
            const existing = header.data.values?.[0] || [];
            if (existing.length && (existing.length !== SHEET_HEADERS.length || existing.some((v, i) => v !== SHEET_HEADERS[i]))) {
                // Relabelling headers without moving existing cells corrupts older schemas.
                throw new UserError('Google Sheets tab headers differ. Specify a separate empty tab in GOOGLE_SHEET_TAB.');
            }
            if (!existing.length) {
                await api.spreadsheets.values.update({ spreadsheetId, range: range + '!A1', valueInputOption: 'RAW',
                    requestBody: { values: [SHEET_HEADERS] } }, options);
            }
            const idColumn = columnName(SHEET_HEADERS.indexOf('Lead ID') + 1);
            const ids = await api.spreadsheets.values.get({ spreadsheetId, range: range + '!' + idColumn + ':' + idColumn }, options);
            const row = (ids.data.values || []).findIndex(cells => cells[0] === lead.id);
            const values = [sheetRow(lead, env)];
            // Check the durable ID again on every retry, including after a network timeout.
            if (row >= 1) {
                await api.spreadsheets.values.update({ spreadsheetId, range: range + '!A' + (row + 1), valueInputOption: 'RAW',
                    requestBody: { values } }, options);
            } else {
                await api.spreadsheets.values.append({ spreadsheetId, range: range + '!A:A', valueInputOption: 'RAW',
                    insertDataOption: 'INSERT_ROWS', requestBody: { values } }, options);
            }
            return { tab: title, syncedAt: new Date().toISOString() };
        });
    }
    return { save, configured };
}
